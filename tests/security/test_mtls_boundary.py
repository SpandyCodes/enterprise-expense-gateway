"""
The actual TLS handshake / client-certificate verification happens at the
Nginx layer (see nginx/nginx.conf, ssl_verify_client). These tests verify
the FastAPI application's side of that trust boundary: it must reject
any request that lacks the X-Client-Cert-CN header that Nginx only sets
after successfully verifying a client certificate, and accept requests
that carry it.

A full end-to-end mTLS handshake test (invalid cert / no cert / valid
cert against the live Nginx listener) is documented as a manual
verification step in docs/testing.md, since it requires the certs
generated by scripts/generate_certs.sh and a running nginx container.
"""
import pytest

pytestmark = pytest.mark.security


async def test_internal_endpoint_rejects_request_without_verified_client_header(client):
    resp = await client.post("/internal/integrations/expense-sync", json={"foo": "bar"})
    assert resp.status_code == 401
    assert resp.json()["error"]["code"] == "MTLS_CLIENT_CERT_REQUIRED"


async def test_internal_endpoint_accepts_request_with_verified_client_header(client):
    resp = await client.post(
        "/internal/integrations/expense-sync",
        json={"foo": "bar"},
        headers={"X-Client-Cert-CN": "expense-integration-client"},
    )
    assert resp.status_code == 200
    assert resp.json()["verified_client"] == "expense-integration-client"
